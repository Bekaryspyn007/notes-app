function getStatus(float $temp, int $pulse): string
{
    if ($pulse < 60) {
        return "Check required";
    } elseif ($temp > 37.5 || $pulse > 100) {          
        return "Attention";
    } elseif ($temp <= 37.5 && $pulse >= 60 && $pulse <= 100) { 
        return "Normal";
    } else {
        return "Check required"; 
    }
}

function getStatusClass(string $status): string
{
    if ($status === "Normal") {
        return "badge-normal";
    } elseif ($status === "Attention") {
        return "badge-warning";
    }
    return "badge-critical";
}

function getReason(array $p): string
{
    $reasons = [];
    if ($p["pulse"] < 60)  { $reasons[] = "pulse below 60 bpm"; }
    if ($p["pulse"] > 100) { $reasons[] = "pulse above 100 bpm"; }
    if ($p["temperature"] > 37.5) { $reasons[] = "temperature above 37.5 °C"; }
    return implode(", ", $reasons); 
}

