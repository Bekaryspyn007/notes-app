$avgTemp      = array_sum($temps) / $total;
$avgPulse     = array_sum($pulses) / $total;
$maxPulse     = max($pulses);
$minTemp      = min($temps);
$attentionList  = array_filter($patients, fn($p) => $p["status"] === "Attention");
$attentionCount = count($attentionList);
$problemList    = array_filter($patients, fn($p) => $p["status"] !== "Normal");

$maxPulseName = $patients[array_search($maxPulse, $pulses)]["name"];

